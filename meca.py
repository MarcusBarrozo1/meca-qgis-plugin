    def crop_raster (self):
        '''Read the raster bands and get projection'''
        import osgeo
        import osgeo.ogr as ogr

        #First: Take the raster from the select_raster method
        rasterB2 = self.select_rasterb2
        rasterB3 = self.select_rasterb3
        rasterB4 = self.select_rasterb4
        rasterB8 = self.select_rasterb8

        #Second: Read the raster
        b2 = gdal.Open(rasterB2, osgeo.gdal.GA_ReadOnly)
        b3 = gdal.Open(rasterB3, osgeo.gdal.GA_ReadOnly)
        b4 = gdal.Open(rasterB4, osgeo.gdal.GA_ReadOnly)
        b8 = gdal.Open(rasterB8, osgeo.gdal.GA_ReadOnly)
    
        #Obtain separated geotransform
        geotransform = b2.GetGeoTransform()
        x_min = geotransform[0]
        y_max = geotransform[3]
        x_max = x_min + geotransform[1] * b2.RasterXSize
        y_min = y_max + geotransform[5] * b2.RasterYSize
        

        #Third: Take and read the mask layer from select_layer method
        feat = self.select_feature()
        mask_geom = feat['geometry']
        if mask_geom is None:
            print("No geometry available")
            return
        
        masksimplified = mask_geom.simplify(tolerance = 0)
         
        if masksimplified.isEmpty():
            print("Mask feature has no geometry!")
            return
        
        #Fourth: Set offsets and dimensions for crop the raster
        maskExtent = masksimplified.boundingBox()
        mask_extent = [maskExtent.xMinimum(), maskExtent.yMinimum(), maskExtent.xMaximum(), maskExtent.yMaximum()]
        
        b2_transform = b2.GetGeoTransform()
        raster_origin_y = b2_transform[3]
        offset_x = int((mask_extent[0] + (b2_transform[1] / 2) - b2_transform[0]) / b2_transform[1])
        offset_y = int((raster_origin_y - mask_extent[3]) / abs(b2_transform[5]))
        width = int((mask_extent[2] - mask_extent[0]) / b2_transform[1])
        height = int((mask_extent[3] - mask_extent[1]) / abs(b2_transform[5]))

        #Fifth: Crop each band to bounding box of mask, turn into Numpy Array
        b2_crop = b2.ReadAsArray(offset_x, offset_y, width, height)
        b3_crop = b3.ReadAsArray(offset_x, offset_y, width, height)
        b4_crop = b4.ReadAsArray(offset_x, offset_y, width, height)
        b8_crop = b8.ReadAsArray(offset_x, offset_y, width, height)
        
        b2_crop_transform = (b2_transform[0] + offset_x * b2_transform[1], b2_transform[1], b2_transform[2], 
                            b2_transform[3] + offset_y * b2_transform[5], b2_transform[4], b2_transform[5])

        #Sixth: Mask the crop bands to the layer extension
        mask_layer = ogr.GetDriverByName('Memory').CreateDataSource("")
        mask_layer1 = mask_layer.CreateLayer("mask_layer", geom_type=ogr.wkbPolygon)
        feature = ogr.Feature(mask_layer1.GetLayerDefn())
        ogr_geom = ogr.CreateGeometryFromWkt(masksimplified.asWkt())
        feature.SetGeometry(ogr_geom)
        mask_layer1.CreateFeature(feature)
        feature.Destroy()

        mask_rasterize = gdal.GetDriverByName('MEM').Create('', width, height, 1, gdal.GDT_Byte)
        mask_rasterize.SetGeoTransform(b2_crop_transform)
        gdal.RasterizeLayer(mask_rasterize, [1], mask_layer1, burn_values=[1])
        mask_np = mask_rasterize.ReadAsArray()

        b2_mask = np.where(mask_np, b2_crop, 1)
        b3_mask = np.where(mask_np, b3_crop, 1)
        b4_mask = np.where(mask_np, b4_crop, 1)
        b8_mask = np.where(mask_np, b8_crop, 1)

        b2_mascara = b2_mask/10000
        b3_mascara = b3_mask/10000
        b4_mascara = b4_mask/10000
        b8_mascara = b8_mask/10000

        del b2
        del b3
        del b4 
        del b8

        return {
            'mask_extent' : mask_extent,
            'b2_transform' : b2_transform,
            'b2_crop_transform' : b2_crop_transform,
            'b2_mascara' : b2_mascara,
            'b3_mascara' : b3_mascara,
            'b4_mascara' : b4_mascara,
            'b8_mascara' : b8_mascara
        }
    
    def get_model_variables (self):
        '''Reads the gui user inputs and assigns to its model variables'''

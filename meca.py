    def RR (self):
        '''Calculates the Net Solar Radiation'''
        
        RG = self.RG()
        
        hr_alb = self.albedo()
        
        RR = hr_alb * RG
        
        return RR

    def Emiss_atm (self):
        '''Atmospheric Emissivity calculation'''

        Transm = self.RsTrans()
        
        Emiss_atm = 0.9364 * (((-1) * np.log(Transm)) ** 0.1135)
        Emiss_atm [Emiss_atm > 1] = 1
        
        return Emiss_atm

    def RLdown_wm2 (self):
        '''Calculates the Downward Longwave Radiation in Watts per square meter'''
        
        Tmean = self.Tmean()

        Emiss_atm = self.Emiss_atm()
        
        RLdown_wm2 = (Emiss_atm * 5.67 * (10 ** (-8)) * ((Tmean + 273.15) ** 4))
        
        return RLdown_wm2

    def RL_down (self):
        '''Downward Longwave Radiation'''
        
        RLdown_wm2 = self.RLdown_wm2()
        
        RL_down = RLdown_wm2 / 11.6
        
        return RL_down

    def RL_up (self):
        '''Upward Longwave Radiation'''
        
        RG = self.RG()
        
        RR = self.RR()
        RL_down = self.RL_down()
        Rn_MJ = self.Rn_MJ()
        
        RL_up = (RG - RR + RL_down - Rn_MJ)
        
        return RL_up

    def Esurf (self):
        '''Calculates the Surface Emissivity'''

        ndvi = self.ndvi()
        
        Esurf_r1 = np.copy(ndvi)
        Esurf_r1[ndvi < 0] = 1
        Esurf_r1[ndvi >= 0] = np.nan
        
        Esurf_r2 = 1.0035 + 0.0589 * np.log(ndvi)
        
        Esurf = np.where(np.isnan(Esurf_r1), Esurf_r2, Esurf_r1)

        return Esurf

    def TS24 (self):
        '''Calculates the 24-hour average Land Surface Temperature'''

        RL_up = self.RL_up()
        Esurf = self.Esurf()

        TS24 = ((RL_up * 11.6) / ((Esurf * 5.67) * (10 **(-8)))) ** (0.25)
        TS24 [TS24 < 273.15] = np.nan
        
        
        #Write Raster to file
        values = self.crop_raster()
        adjusted_geotransform = values['b2_crop_transform']
        
        output_direc = self.output_directory()
        out_file = os.path.join(output_direc, 'Temperatura de Superfície.tif')
        
        driver = gdal.GetDriverByName('GTiff')
        out_raster = driver.Create(out_file, TS24.shape[1], TS24.shape[0], 1, gdal.GDT_Float32)
        out_raster.SetGeoTransform(adjusted_geotransform)
        out_band = out_raster.GetRasterBand(1)
        out_band.WriteArray(TS24)

        srs = osr.SpatialReference()
        srs.ImportFromEPSG(4326)  # This is WGS84
        out_raster.SetProjection(srs.ExportToWkt())

        out_band.FlushCache()
        out_raster = None

        return TS24
        
    def kc (self):
        '''Calculates the Crop Coefficient'''
        
        TS24 = self.TS24()
        hr_alb = self.albedo()

        ndvi = self.ndvi()
        ndvi = np.where(ndvi <= 0, np.nan, ndvi)

        a = 1.8
        b = -0.008

        kc = np.exp(a + b * ((TS24 - 273.15) / (hr_alb * ndvi)))
        np.seterr(invalid = 'ignore')

        #Write Raster to file
        values = self.crop_raster()
        adjusted_geotransform = values['b2_crop_transform']
        
        driver = gdal.GetDriverByName('GTiff')
        
        output_direc = self.output_directory()
        out_file = os.path.join(output_direc, 'kc_origin.tif')
        
        out_raster = driver.Create(out_file, kc.shape[1], kc.shape[0], 1, gdal.GDT_Float32)
        out_raster.SetGeoTransform(adjusted_geotransform)
        out_band = out_raster.GetRasterBand(1)
        out_band.WriteArray(kc)
        srs = osr.SpatialReference()
        srs.ImportFromEPSG(4326)  # This is WGS84
        out_raster.SetProjection(srs.ExportToWkt())

        out_band.FlushCache()
        out_raster = None

        return kc

    def kc_scale (self):

        kc = self.kc()

        kc_min = np.nanmin(kc)
        kc_max = np.nanmax(kc)
        print(f"Kc min: {kc_min}, Kc max: {kc_max}")

        if kc_max <= 0.9:
            min = 0
            max = 0.3
        elif kc_max <= 1.8:
            min = 0
            max = 0.6
        elif kc_max <= 2.7:
            min = 0
            max = 0.9
        elif kc_max <= 3.6:
            min = 0
            max = 1.2
        
        if kc_max == 1.2:
            return kc
        else:
            kc_scale = ((kc - kc_min) / (kc_max - kc_min)) * (max - min) + min
        
        
        #Write Raster to file
        values = self.crop_raster()    
        adjusted_geotransform = values['b2_crop_transform']
        
        driver = gdal.GetDriverByName('GTiff')
        
        output_direc = self.output_directory()
        out_file = os.path.join(output_direc, 'coeficiente de cultura.tif')
        
        out_raster = driver.Create(out_file, kc_scale.shape[1], kc_scale.shape[0], 1, gdal.GDT_Float32)
        out_raster.SetGeoTransform(adjusted_geotransform)
        out_band = out_raster.GetRasterBand(1)
        out_band.WriteArray(kc_scale)
        srs = osr.SpatialReference()
        srs.ImportFromEPSG(4326)  # This is WGS84
        out_raster.SetProjection(srs.ExportToWkt())

        out_band.FlushCache()
        out_raster = None

        return kc_scale

    def HS (self):
        '''Calculates the Reference Evapotranspiration based on Hargreaves and Samani (1985)'''
        
        vrb = self.get_model_variables()
        Tmax = vrb['Tmax']
        Tmin = vrb['Tmin']
        
        Tmean = self.Tmean()

        Ra = self.Ra()

        ET0 = 0.0023 * (Tmax - Tmin)**0.5 * (Tmean + 17.8) * Ra * 0.408

        return ET0

    def ETr (self):
        '''Calculates the Evapotranspiration'''
        
        kc = self.kc_scale()
        ET0 = self.HS()
        
        ETr = kc * ET0
        
        #Write Raster to file
        values = self.crop_raster()
        adjusted_geotransform = values['b2_crop_transform']
        
        driver = gdal.GetDriverByName('GTiff')

        output_direc = self.output_directory()

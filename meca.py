    def Tmean (self):
        '''Gets the average temperature of the air, daily'''
        vrb = self.get_model_variables()
        
        Tmax = vrb['Tmax']
        Tmin = vrb['Tmin']

        Tmean = (Tmax + Tmin) / 2

        return Tmean
    
    def doy (self):
        '''Transform the datetime of image acquisition to day of year'''
        vrb = self.get_model_variables()
        date = vrb['date']
        
        try:
            from datetime import datetime
            date_obj = datetime.strptime(date, '%Y-%m-%d')
            
            doy = int(date_obj.strftime('%j'))
        
        except ValueError:
            self.dlg.doy_line.setText("Data inválida, use o formato 'AAAA-MM-DD'")
        
        return doy

    def albedo (self):
        '''Calculates the albedo based on the raster bands'''
        
        values = self.crop_raster()
        
        b2_mascara = values['b2_mascara']
        b3_mascara = values['b3_mascara']
        b4_mascara = values['b4_mascara']
        b8_mascara = values['b8_mascara']
        
        #albedo calculation
        top_alb = b2_mascara * 0.32 + b3_mascara * 0.26 + b4_mascara * 0.25 + b8_mascara + 0.17
        sur_alb = 0.6054 * top_alb + 0.0797
        hr_alb = 1.0223 * sur_alb + 0.0149
        

        #Write Raster to file
        adjusted_geotransform = values['b2_crop_transform']
        
        output_direc = self.output_directory()
        out_file = os.path.join(output_direc, 'albedo.tif')

        driver = gdal.GetDriverByName('GTiff')
        out_raster = driver.Create(out_file, hr_alb.shape[1], hr_alb.shape[0], 1, gdal.GDT_Float32)
        out_raster.SetGeoTransform(adjusted_geotransform)
        out_band = out_raster.GetRasterBand(1)
        out_band.WriteArray(hr_alb)
        
        srs = osr.SpatialReference()
        srs.ImportFromEPSG(4326)  # This is WGS84
        out_raster.SetProjection(srs.ExportToWkt())

        out_band.FlushCache()
        out_raster = None

        return hr_alb

    def ndvi (self):
        '''Calculates the Normalized Difference Vegetation Index based on the Red and Shortwave Infrared Bands'''
        
        #Call crop_raster to retrieve the derived values needed
        values = self.crop_raster()
        
        b4_mascara = values['b4_mascara']
        b8_mascara = values['b8_mascara']
        
        #NDVI calculation
        ndvi = (b8_mascara - b4_mascara) / (b8_mascara + b4_mascara)


        #Write Raster to file     
        adjusted_geotransform = values['b2_crop_transform']
        
        output_direc = self.output_directory()
        out_file = os.path.join(output_direc, 'ndvi.tif')
        
        driver = gdal.GetDriverByName('GTiff')
        out_raster = driver.Create(out_file, ndvi.shape[1], ndvi.shape[0], 1, gdal.GDT_Float32)
        out_raster.SetGeoTransform(adjusted_geotransform)
        out_band = out_raster.GetRasterBand(1)
        out_band.WriteArray(ndvi)

        srs = osr.SpatialReference()
        srs.ImportFromEPSG(4326)  # This is WGS84
        out_raster.SetProjection(srs.ExportToWkt())

        out_band.FlushCache()
        out_raster = None

        return ndvi
        
    def transform (self):
        '''Performs spatial transformations related to geographic coordinates and time'''
        
        values = self.crop_raster()
        b2_mascara = values['b2_mascara']
        b2_transform = values['b2_crop_transform']
        
        doy = self.doy()
        
        rows, cols = b2_mascara.shape
        row_indices, col_indices = np.meshgrid(np.arange(cols), np.arange(rows))
        
        long = b2_transform[0] + col_indices * b2_transform[1] + row_indices * b2_transform[2]
        lati = b2_transform[3] + col_indices * b2_transform[4] + row_indices * b2_transform[5]

        # Calculation related to the time
        map1 = (long / long.max()) * ((2 * math.pi) / 365) * (doy - 1)

        return {
            'long_crop' : long,
            'lati_crop' : lati,
            'map1' : map1
        }

    def Et (self):
        '''Calculates the Solar Zenith Angle'''
        values = self.transform()
        map1 = values['map1']
        
        Et = (0.000075 + 0.001868 * np.cos(map1) - 0.032077 * np.sin(map1) - 0.014615 * np.cos(2 * map1) - 0.04089 * np.sin(2 * map1))
        
        return Et
        
    def LAT (self):
        '''Local Apparent Time, for solar position calculation'''
        
        values = self.transform()
        long_crop = values['long_crop']
        Et = self.Et()

        LAT = (13 + (4 * long_crop / 60) + (Et / 60))

        return LAT
    
    def solDec (self):
        '''Calculates the Solar Declination'''
        
        values = self.transform()
        map1 = values['map1']
        
        Dec = 0.006918 - 0.399912 * np.cos(map1) + 0.70257 * np.sin(map1) + 0.006758 * np.cos(2 * map1) + 0.000907 * np.sin(2 * map1) - 0.002697 * np.cos(3 * map1) + 0.00148 * np. sin(3 * map1)

        return Dec
    
    def solElev (self):
        '''Calculates the solar elevation angle'''
        
        solDec = self.solDec()
        LAT = self.LAT()
        
        values = self.transform()
        lati = values['lati_crop']
        long = values['long_crop']
        
        lati_rad = np.deg2rad(lati)
        long_rad = np.deg2rad(long)
        
        solDec_rad = np.deg2rad(solDec)
        
        solTime = 15 * (LAT - 12)
        
        solar_elev_angle = np.rad2deg(np.arcsin(
            np.sin(solDec_rad) * np.sin(lati_rad) +
            np.cos(solDec_rad) * np.cos(lati_rad) * np.cos(np.deg2rad(solTime))
        ))
        
        return solar_elev_angle
    
    def Gsc (self):
        '''Calculates the Solar Constant'''
        
        Gsc = 0.0820
        
        return Gsc
    
    def dr (self):
        '''Defines Sun-Earth relative distance'''
        
        doy = self.doy()

        dr = 1 + 0.033 * np.cos(((2 * np.pi) / 365) * doy)

        return dr
    
    def Wsun (self):
        '''Calculates the Sunset Solar Angle Radiation'''

        values = self.transform()
        lati = values['lati_crop']
        Lati_rad = np.deg2rad(lati)
        
        solDec = self.solDec()

        Ws = np.arccos(-np.tan(Lati_rad) * np.tan(solDec))
        
        return Ws

    def Ra (self):
        '''Calculates the Solar Radiation based on Hargreaves and Samani (1982)'''

        values = self.transform()
        lati = values['lati_crop']
        Lati_rad = np.deg2rad(lati)

        Gsc = self.Gsc()
        dr = self.dr()
        Wsun = self.Wsun()
        solDec = self.solDec()


        Ra = ((24 * 60) / np.pi) * Gsc * dr * (Wsun * np.sin(Lati_rad) * np.sin(solDec) + np.cos(Lati_rad) * np.cos(solDec) * np.sin(Wsun))

        return Ra

    def RG (self):
        '''Estimates Global Radiation approximation by Beer-Lambert Law'''
        
        Ra = self.Ra()
        solElev = self.solElev()
        
        solElev_rad = np.deg2rad(solElev)

        atmospheric_transmittance = 0.74 #Mean value for Ceará by ANDRADE 2008.

        RG = Ra * atmospheric_transmittance**(1 / np.sin(solElev_rad))

        return RG

    def W (self):
        '''Calculates the solar time angle'''

        LAT = self.LAT()
        
        W = 15 * (LAT - 12) * (np.pi / 180)

        return W

    def cos_zwn (self):
        '''Calculates the cosine of the zenith angle'''
        
        values = self.transform()
        lati_crop = values['lati_crop']
        Dec = self.solDec()
        W = self.W()
        
        cos_zwn = np.sin(lati_crop * np.pi / 180) * np.sin(Dec) + np.cos(lati_crop * np.pi / 180) * np.cos(Dec) * np.cos(W)

        return cos_zwn

    def E0 (self):
        '''Calculates the Extraterrestrial Solar Radiation'''

        values = self.transform()
        map1 = values['map1']

        E0 = (1.00011 + 0.034221 * np.cos(map1) + 0.00128 * np.sin(map1) + 0.000719 * np.cos(2 * map1) + 0.000077 * np.sin(2 * map1))

        return E0

    def R (self):
        '''Calculates the Solar Radiation'''
        
        values = self.transform()
        lati_crop = values['lati_crop']
        
        Dec = self.solDec()
        Ws = self.Wsun()
        
        R = (Ws * np.sin(lati_crop * np.pi / 180) * np.sin(Dec)) + (np.cos(lati_crop * np.pi / 180) * np.cos(Dec) * np.sin(Ws))

        return R

    def RsTop (self):
        '''Calculates the Top of Atmosphere Solar Radiation'''

        values = self.crop_raster()
        b2_mascara = values['b2_mascara']
        
        E0 = self.E0()
        R = self.R()

        RsTop_aux = (1367 / np.pi) * E0 * R
        RsTop = RsTop_aux.reshape(b2_mascara.shape[0], b2_mascara.shape[1])

        return RsTop
    
    def RsTrans (self):
        '''Calculates the Transmissivity of Solar Radiation'''

        RG = self.RG()
        
        RsTop = self.RsTop()
        
        Transm = (RG * 11.6) / RsTop

        return Transm

    def Rn_coeff (self):
        '''Calculates the Net Radiation Coefficient'''
        
        Tmean = self.Tmean()
        
        Rn_coeff = 6.99 * Tmean - 39.99

        return Rn_coeff

    def Rn (self):
        '''Calculates the Net Radiation'''
        
        RG = self.RG()
        
        hr_alb = self.albedo()
        Rn_coeff = self.Rn_coeff()
        Transm = self.RsTrans()
        
        Rn = ((1 - hr_alb) * (RG * 11.6)) - (Rn_coeff * Transm)
        
        return Rn

    def Rn_MJ (self):
        '''Net Radiation in megajoules'''

        Rn = self.Rn()
        
        Rn_MJ = Rn / 11.6

        return Rn_MJ

    def slope (self):
        '''This function calculates the slope of the saturation vapour pressure-temperature curve'''
        
        Tmean = self.Tmean()

        slope = (4098 * (0.6108 * np.exp((17.27 * (Tmean)) / ((Tmean) + 237.3))) / ((Tmean) + 237.3) ** 2)

        return slope

    def LEeq (self):
        '''This function calculates the Latent Heat of Evaporation'''

        slope = self.slope()
        Rn = self.Rn()
        
        LEeq = (slope * Rn) / (slope + 0.066)
        
        return LEeq

    def close (self):

        slope = self.slope()
        slope.close()
        Rn_coeff = self.Rn_coeff()
        Rn_coeff.close()
        RsTop = self.RsTop()
        RsTop.close()
        RsTop_aux = self.RsTop_aux()
        RsTop_aux.close()
        R = self.R()

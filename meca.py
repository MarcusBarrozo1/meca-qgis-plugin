    def mean_status (self):
        '''Retrieves the average of kc, ETr and vol_m3 for the status_report func'''
        kc = self.kc_scale()
        ETr = self.ETr()
        vol_m3, area_ha, area_m2 = self.consumption()

        masked_vol = np.ma.masked_array(vol_m3, np.isnan(vol_m3)) 
        mean_vol = np.average(masked_vol)
        
        masked_et = np.ma.masked_array(ETr, np.isnan(ETr)) 
        mean_et = np.average(masked_et)
        
        masked_kc = np.ma.masked_array(kc, np.isnan(kc)) 
        mean_kc = np.average(masked_kc)

        return mean_vol, mean_et, mean_kc
    
